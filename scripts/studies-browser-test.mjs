import assert from 'node:assert/strict'
import {spawn} from 'node:child_process'
import {mkdtemp,mkdir,rm} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
import {chromium} from 'playwright'

const work=await mkdtemp(join(tmpdir(),'charcoal-studies-'))
const port=process.env.CHARCOAL_TEST_PORT??'4323'
const url=`http://127.0.0.1:${port}`
let service,browser,page
const api=async(path='/state',options)=>{
  const response=await fetch(url+'/api'+path,options)
  assert.equal(response.ok,true,await response.clone().text())
  return response.json()
}
const until=async(predicate)=>{
  const start=Date.now()
  while(Date.now()-start<20000){const value=await predicate();if(value)return value;await new Promise(r=>setTimeout(r,80))}
  assert.fail('Timed out waiting for study state')
}
const saved=predicate=>until(async()=>{const {workspace}=await api();return workspace&&predicate(workspace)&&workspace})
try {
  service=spawn(process.execPath,[process.env.CHARCOAL_TEST_SERVER??'server/index.mjs'],{env:{...process.env,
    CHARCOAL_PORT:port,CHARCOAL_DEMO:'1',CHARCOAL_FIXTURE:'1',CHARCOAL_DATA_DIR:work},stdio:['ignore','pipe','pipe']})
  await new Promise((resolve,reject)=>{
    let log=''
    service.stderr.on('data',chunk=>log+=chunk)
    service.stdout.on('data',chunk=>{if(String(chunk).includes('Charcoal on'))resolve()})
    service.once('exit',()=>reject(new Error(log)))
  })
  browser=await chromium.launch({channel:'chrome'})
  page=await browser.newPage({viewport:{width:1248,height:800},reducedMotion:'reduce',acceptDownloads:true})
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(url)
  const tile=id=>page.locator(`.tile[data-id="${id}"] .board-tile-hit`)
  const screenshot=async name=>{await mkdir('test-results',{recursive:true});await page.screenshot({path:`test-results/${name}.png`})}
  const settings=async(mode,count)=>{
    await page.locator('#setBtn').click()
    await page.getByRole('radio',{name:mode,exact:true}).click()
    if(count)await page.getByRole('radio',{name:String(count),exact:true}).click()
    await page.keyboard.press('Escape')
  }
  async function send(count){
    const before=new Set((await api('/runs')).runs.map(run=>run.id))
    const prompt=await page.locator('#prompt').textContent()
    let submissions=0
    const countRequest=request=>{if(request.method()==='POST'&&new URL(request.url()).pathname==='/api/runs')submissions++}
    page.on('request',countRequest)
    await page.getByRole('button',{name:'Send to Sunburst'}).click()
    await page.locator('#prompt').press('Enter')
    await page.locator('#prompt').press('Enter')
    await page.locator('#send[data-sent="true"]').waitFor()
    if(count>1) assert.equal(await page.getByRole('status',{name:'Generating images'}).isVisible(),true,'generation stays visible after submission is accepted')
    assert.equal(await page.locator('#send').getAttribute('aria-label'),'Submitted')
    assert.equal(await page.locator('#send').innerText(),'','submission feedback is an icon, not visible status text')
    assert.equal(await page.getByText(/^(Sending|Sent)[.!…]?$/).count(),0)
    assert.equal(await page.locator('#prompt').textContent(),prompt,'accepted submissions retain the typed prompt')
    assert.equal(await page.locator('#send').isDisabled(),true)
    const complete=await until(async()=>{
      const runs=(await api('/runs')).runs.filter(run=>!before.has(run.id))
      if(runs.some(run=>run.status==='failed'||run.status==='uncertain'))assert.fail(JSON.stringify(runs))
      return runs.length===count&&runs.every(run=>run.status==='done')&&runs
    })
    assert.equal(submissions,count,'repeated Enter must not submit a duplicate batch')
    page.off('request',countRequest)
    await page.locator('#send[data-sent="true"]').waitFor({state:'hidden'})
    await until(async()=>await page.locator('#send').isEnabled())
    assert.equal(await page.getByRole('status',{name:'Generating images'}).count(),0,'indicator clears when the batch finishes')
    return complete
  }
  await tile('layout').click()
  await page.getByRole('button',{name:'Pin Layout sketch',exact:true}).click()
  await saved(w=>w.pinnedIds?.includes('layout'))
  await page.getByRole('button',{name:'Pinned (1)',exact:true}).click()
  const pins=page.getByRole('region',{name:'Pinned images'})
  assert.equal(await pins.getByRole('button',{name:'Refine Layout sketch'}).isVisible(),true)
  await page.mouse.click(70,300)
  assert.equal(await pins.isVisible(),true,'drawer stays open during canvas work')
  const download=page.waitForEvent('download')
  await pins.getByRole('link',{name:'Download Layout sketch'}).click()
  assert.ok((await download).suggestedFilename())
  await screenshot('studies-pins')
  await page.keyboard.press('Escape')
  await tile('layout').click()
  await page.keyboard.press('Delete')
  await saved(w=>w.deletedImageIds?.includes('layout')&&w.pinnedIds?.includes('layout'))
  assert.equal(await tile('layout').count(),0,'removing from canvas does not remove its pin')
  await page.getByRole('button',{name:'Pinned (1)',exact:true}).click()
  assert.equal(await pins.getByRole('button',{name:'Refine Layout sketch'}).isVisible(),true)
  await pins.getByRole('button',{name:'Find Layout sketch on canvas',exact:true}).click()
  await tile('layout').waitFor()
  await saved(w=>!w.deletedImageIds?.includes('layout')&&w.pinnedIds?.includes('layout'))
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Add Layout sketch to prompt',exact:true}).click()
  await page.getByRole('button',{name:'Add Two walkers to prompt',exact:true}).click()
  await saved(w=>w.prompt.includes('[[image:layout]]')&&w.prompt.includes('[[image:walkers]]'))
  assert.equal(await page.locator('#prompt [data-image-id]').count(),2)
  await page.locator('#prompt').fill('A researcher follows a winding path toward a small observatory. Use ')
  await page.getByRole('button',{name:'Insert reference to Layout sketch',exact:true}).click()
  await page.keyboard.insertText('for the diagonal rhythm and loose brushwork; avoid its subject matter and palette.')
  await page.getByRole('button',{name:'Insert reference to Layout sketch',exact:true}).focus()
  await page.keyboard.press('Alt+ArrowRight')
  await saved(w=>w.attachments[1]==='layout'&&w.prompt.includes('diagonal'))
  await screenshot('studies-inline-reference')
  await page.reload()
  await page.getByRole('button',{name:'Pinned (1)',exact:true}).waitFor()
  await settings('B&W thumbnails',3)
  await page.locator('#setBtn').click()
  assert.equal(await page.locator('#setPop textarea').count(),0,'no preset composition fields')
  await page.getByRole('radiogroup',{name:'Quality',exact:true}).getByRole('radio',{name:'High',exact:true}).click()
  assert.doesNotMatch(await page.locator('#styleBtn').innerText(),/Style paused/)
  await screenshot('studies-composition-settings')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Full prompt',exact:true}).click()
  assert.match(await page.locator('#fullPrompt').innerText(),/Use Image 2 for the diagonal rhythm/s)
  await page.getByRole('button',{name:'Full prompt',exact:true}).click()
  let plans=0
  const countPlans=request=>{if(request.method()==='POST'&&new URL(request.url()).pathname==='/api/composition-plans')plans++}
  page.on('request',countPlans)
  const studies=await send(3)
  page.off('request',countPlans)
  assert.equal(plans,1,'the entire composition batch shares one planning call')
  assert.equal(new Set(studies.map(run=>run.effectivePrompt)).size,3)
  assert.ok(studies.every(run=>run.settings.count==='1'&&run.settings.quality==='High'&&run.settings.complexity==='High'&&run.style?.rules.length>0))
  assert.ok(studies.every(run=>/Render the supplied scene with fixture treatment/.test(run.effectivePrompt)))
  assert.ok(studies.every(run=>run.inputs.length===2&&run.inputs.includes('walkers')&&run.inputs.includes('layout')))
  assert.ok(studies.every(run=>run.style.rules.every(rule=>!rule.prompt||rule.prompt.includes('Translate colour requirements into grayscale values'))))
  assert.ok((await api()).workspace.styleStore.styles.every(style=>style.rules.every(rule=>!rule.prompt.includes('For this grayscale composition/value study'))),'saved styles stay unchanged')
  for (const run of studies) {
    assert.doesNotMatch(run.effectivePrompt,/A researcher follows a winding path toward a small observatory/)
    assert.doesNotMatch(run.effectivePrompt,/Assigned composition: Fixture composition/)
    assert.doesNotMatch(run.effectivePrompt,/Consider the full set before rendering alternative/)
    assert.doesNotMatch(run.effectivePrompt,/distant viewpoint|Look down from above|Direction for this image/)
  }
  for (let index=1;index<=3;index++) assert.ok(studies.some(run=>run.effectivePrompt.includes(`fixture treatment ${index}`)))
  assert.ok(studies.every(run=>run.rect.width===144))
  await settings('Illustration',2)
  await page.locator('#prompt').fill('Explore two lighting treatments for the attached scene.')
  await page.locator('#setBtn').click()
  await page.getByRole('radiogroup',{name:'Vary',exact:true}).getByRole('radio',{name:'Lighting',exact:true}).click()
  await page.keyboard.press('Escape')
  plans=0
  page.on('request',countPlans)
  const lighting=await send(2)
  page.off('request',countPlans)
  assert.equal(plans,1,'whole-image lighting alternatives share one plan')
  assert.ok(lighting.every(run=>run.target===null&&run.inputs.length===2&&run.guideMode==='whole'))
  assert.ok(lighting.every((run,index)=>run.effectivePrompt.includes(`fixture treatment ${index+1}`)))
  await page.locator('#setBtn').click()
  await page.getByRole('button',{name:'Use suggestion',exact:true}).click()
  await page.keyboard.press('Escape')
  await settings('Illustration',1)
  await page.getByRole('button',{name:'Pinned (1)',exact:true}).click()
  await pins.getByRole('button',{name:'Refine Layout sketch'}).click()
  await page.getByRole('radio',{name:'Annotate',exact:true}).click()
  await page.getByRole('radio',{name:'Arrow',exact:true}).click()
  let box=await page.locator('.paint-surface').boundingBox()
  await page.mouse.move(box.x+box.width*.2,box.y+box.height*.3)
  await page.mouse.down()
  await page.mouse.move(box.x+box.width*.7,box.y+box.height*.6,{steps:8})
  await page.mouse.up()
  await page.getByRole('radio',{name:'Text note',exact:true}).click()
  await page.mouse.click(box.x+box.width*.3,box.y+box.height*.4)
  await page.getByRole('textbox',{name:'Annotation text',exact:true}).fill('Keep this area quiet; move the focal shape right')
  await page.getByRole('button',{name:'Save note',exact:true}).click()
  await screenshot('studies-annotate')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await saved(w=>w.guides.layout?.some(mark=>mark.tool==='text')&&w.guideMode==='markup')
  await page.reload()
  await page.locator('#prompt').fill('Follow the redline directions.')
  const [annotated]=await send(1)
  assert.equal(annotated.guideMode,'markup')
  assert.ok(annotated.guide.some(mark=>mark.tool==='arrow'))
  assert.match(annotated.effectivePrompt,/editorial annotations, not artwork/)
  assert.ok(annotated.guide.some(mark=>mark.text?.includes('Keep this area quiet')))
  await page.locator('#prompt').fill('Explore a restrained monochrome palette.')
  await page.locator('#setBtn').click()
  const vary=page.getByRole('radiogroup',{name:'Vary',exact:true})
  assert.equal(await vary.getByRole('radio',{name:'Colour',exact:true}).getAttribute('aria-checked'),'true')
  assert.equal(await page.getByText('Suggested: Colour',{exact:true}).isVisible(),true)
  await vary.getByRole('radio',{name:'Style',exact:true}).click()
  assert.equal(await vary.getByRole('radio',{name:'Style',exact:true}).getAttribute('aria-checked'),'true')
  assert.equal(await page.getByText('Suggestion: Colour',{exact:true}).isVisible(),true)
  await page.keyboard.press('Escape')
  await page.locator('#prompt').fill('Adjust the lighting over the quiet shapes.')
  await page.locator('#setBtn').click()
  assert.equal(await vary.getByRole('radio',{name:'Style',exact:true}).getAttribute('aria-checked'),'true','manual variation survives prompt changes')
  assert.equal(await page.getByText('Suggestion: Lighting',{exact:true}).isVisible(),true)
  await page.keyboard.press('Escape')
  await page.locator('#prompt').fill('Explore a restrained monochrome palette.')
  await page.locator('#setBtn').click()
  await page.getByRole('button',{name:'Use suggestion',exact:true}).click()
  await page.getByRole('radiogroup',{name:'Variations',exact:true}).getByRole('radio',{name:'3',exact:true}).click()
  assert.equal(await vary.getByRole('radio',{name:'Colour',exact:true}).getAttribute('aria-checked'),'true')
  await page.keyboard.press('Escape')
  const colours=await send(3)
  assert.ok(colours.every(run=>run.target==='layout'&&run.effectivePrompt.includes('Render the supplied scene with fixture treatment')))
  assert.equal(new Set(colours.map(run=>run.effectivePrompt)).size,3)
  await page.getByRole('button',{name:'Pinned (1)',exact:true}).click()
  await pins.getByRole('button',{name:'Refine Layout sketch'}).click()
  await page.getByRole('radio',{name:'Edit area',exact:true}).click()
  box=await page.locator('.paint-surface').boundingBox()
  const mark=()=>page.mouse.click(box.x+box.width*.46,box.y+box.height*.42)
  await mark()
  await saved(w=>w.guideMode==='mask')
  await page.getByRole('radio',{name:'Erase',exact:true}).click()
  await page.getByRole('slider',{name:'Brush size'}).press('End')
  await mark()
  await saved(w=>w.guideMode==='markup')
  await page.getByRole('radio',{name:'Paint',exact:true}).click()
  await page.getByRole('slider',{name:'Brush size'}).press('Home')
  await mark()
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await saved(w=>w.guideMode==='mask')
  await page.locator('#prompt').fill('Gently darken the pencil shading beneath the figure.')
  await page.locator('#setBtn').click()
  assert.equal(await vary.count(),0)
  await page.getByRole('radiogroup',{name:'Variations',exact:true}).getByRole('radio',{name:'2',exact:true}).click()
  await page.keyboard.press('Escape')
  plans=0
  page.on('request',countPlans)
  const edits=await send(2)
  page.off('request',countPlans)
  assert.equal(plans,1,'painted variations coordinate constrained local edits')
  assert.ok(edits.every(run=>run.guideMode==='mask'&&/Treat the mask as a location guide/.test(run.effectivePrompt)))
  assert.ok(edits.every(run=>run.candidates[0].checks.some(check=>check.title==='Beyond the blend')))
  const bundle=await api('/project')
  assert.ok(bundle.workspace.pinnedIds.includes('layout'))
  assert.ok(Object.values(bundle.workspace.runBriefs).some(brief=>brief.prompt.includes('avoid its subject matter and palette')))
  assert.ok(bundle.workspace.guides.layout.some(mark=>mark.tool==='text'))
  await api('/project',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(bundle)})
  await page.reload()
  await page.getByRole('button',{name:'Workspace, Board 1',exact:true}).click()
  await page.getByRole('button',{name:'New board',exact:true}).click()
  await page.getByLabel('Board name',{exact:true}).fill('Separate studies')
  await page.getByRole('button',{name:'Create board',exact:true}).click()
  await page.getByRole('button',{name:'Workspace, Separate studies',exact:true}).waitFor()
  await page.getByRole('button',{name:'Pinned',exact:true}).click()
  assert.match(await pins.innerText(),/Pin promising images/)
  assert.equal(await pins.getByRole('button',{name:'Refine Layout sketch'}).count(),0,'pins stay board-specific')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Workspace, Separate studies',exact:true}).click()
  await page.getByRole('button',{name:'Board 1',exact:true}).click()
  await page.getByRole('button',{name:'Pinned (1)',exact:true}).click()
  await pins.waitFor()
  await page.setViewportSize({width:390,height:720})
  const bounds=await pins.boundingBox()
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=391)
  await screenshot('studies-pins-narrow')
  await pins.getByRole('button',{name:'Unpin Layout sketch',exact:true}).click()
  await saved(w=>w.pinnedIds?.length===0)
  assert.match(await pins.innerText(),/Pin promising images/)
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'Insert reference to Two walkers',exact:true}).click()
  assert.equal(await page.locator('#prompt [data-image-id="walkers"]').count(),1)
  const composerBounds=await page.locator('#composer').boundingBox()
  assert.ok(composerBounds.x>=0&&composerBounds.x+composerBounds.width<=391,'inline references fit narrow viewport')
  await screenshot('studies-reference-narrow')
  await settings('B&W thumbnails',3)
  await page.locator('#setBtn').click()
  assert.equal(await page.locator('#setPop textarea').count(),0)
  const settingsBounds=await page.locator('#setPop').boundingBox()
  assert.ok(settingsBounds.x>=0&&settingsBounds.x+settingsBounds.width<=391,'study controls fit narrow viewport')
  await screenshot('studies-composition-narrow')
  await page.keyboard.press('Escape')
  assert.deepEqual(errors,[])
  console.log('Studies browser passed: inline references, composition planning, annotations, masked edits and erasing, variation controls, optimistic submission, pins, board isolation, export/reopen and narrow controls.')
} catch(error) {
  if(page){
    await page.screenshot({path:'/tmp/charcoal-studies-flow-failure.png',fullPage:true}).catch(()=>{})
    console.error('Visible UI at failure:',await page.locator('body').innerText().catch(()=>''))
    console.error('Persisted workspace at failure:',JSON.stringify((await api()).workspace))
  }
  throw error
} finally {
  await browser?.close()
  if(service&&service.exitCode===null){const stopped=new Promise(resolve=>service.once('exit',resolve));service.kill();await stopped}
  await rm(work,{recursive:true,force:true})
}
