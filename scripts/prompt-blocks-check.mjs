import assert from 'node:assert/strict'

export async function checkPromptBlocks(page,{savedWorkspace,run,tile}) {
  const canvas=page.getByRole('region',{name:'Canvas',exact:true})
  await canvas.press('0')
  const tool=canvas.getByRole('button',{name:'Prompt text',exact:true})
  const editor=canvas.getByRole('textbox',{name:'Prompt text',exact:true})
  const addBlock=async (x,y,text)=>{
    await tool.click()
    await page.mouse.click(x,y)
    await editor.fill(text)
    await canvas.getByRole('button',{name:'Done',exact:true}).click()
    return canvas.locator('.board-prompt-block').filter({hasText:text})
  }
  const first=await addBlock(300,180,'A lantern in a flooded street.')
  const second=await addBlock(560,180,'Two people wade toward it.')
  const linked=page.getByRole('list',{name:'Prompt blocks',exact:true})
  const start=await first.boundingBox()
  await page.mouse.move(start.x+72,start.y+48)
  await page.mouse.down()
  await page.mouse.move(start.x+95,start.y+48,{steps:5})
  await page.mouse.up()
  assert.ok(Math.abs((await first.boundingBox()).x-start.x-23)<.1)
  await first.click()
  assert.equal(await linked.count(),0)
  for (const [index,block] of [first,second].entries()) {
    await block.hover()
    await block.getByRole('button',{name:'Add to prompt',exact:true}).click()
    assert.equal(await linked.getByRole('listitem').count(),index+1)
  }
  await first.getByRole('button',{name:/^Edit prompt block/}).press('Enter')
  await editor.fill('A paper lantern on a flooded street.')
  await editor.press('Meta+Enter')
  await linked.getByRole('button',{name:/^Find Two people wade toward it/}).press('Alt+ArrowLeft')
  await page.getByRole('button',{name:'Full prompt',exact:true}).click()
  const composed='Two people wade toward it.\n\nA paper lantern on a flooded street.'
  assert.ok((await page.locator('#fullPrompt').innerText()).includes(composed))
  const saved=await savedWorkspace(w=>w.annotations.find(mark=>mark.id===w.promptBlockIds?.[0])?.text==='Two people wade toward it.')
  const stored=saved.annotations.find(mark=>mark.id===saved.promptBlockIds[0])
  assert.equal(stored.kind,'note')
  assert.equal(stored.promptBlock,true)
  await page.reload()
  await linked.getByRole('button',{name:/^Find A paper lantern/}).waitFor()
  await tile(page,'walkers').hover()
  await canvas.getByRole('button',{name:'Add Two walkers to prompt',exact:true}).click()
  const result=await run(page,'',1)
  assert.equal(result.prompt,composed)
  assert.deepEqual(result.inputs,['walkers'])
  assert.ok(result.effectivePrompt.includes(composed))
  await linked.getByRole('button',{name:/Remove A paper lantern/}).click()
  await savedWorkspace(w=>w.promptBlockIds?.length===1)
  const remaining=canvas.locator('.board-prompt-block').filter({hasText:'Two people wade toward it.'})
  await remaining.click()
  await page.keyboard.press('Delete')
  await savedWorkspace(w=>w.promptBlockIds?.length===0)
  await canvas.press('Meta+z')
  await linked.getByRole('button',{name:/^Find Two people wade toward it/}).waitFor()
  console.log('Linked prompt blocks passed: live edits, reordering, reload, generation with references, removal and undo.')
}
